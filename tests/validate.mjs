const topics = data && Array.isArray(data.topics) ? data.topics : [];
const materials = data && Array.isArray(data.materials) ? data.materials : [];

const topicIds = new Set();
for (const [i, t] of topics.entries()) {
  const where = `topic #${i} (${t && t.id})`;
  if (!t || typeof t !== 'object') { fail(`${where}: must be an object`); continue; }
  if (!isText(t.id) || !ID_RE.test(t.id)) fail(`${where}: id must be lowercase letters, digits and dashes`);
  if (topicIds.has(t.id)) fail(`${where}: duplicate topic id`);
  topicIds.add(t.id);
  if (!Number.isInteger(t.grade) || t.grade < 5 || t.grade > 12) fail(`${where}: grade must be an integer 5-12`);
  if (!t.title || !isText(t.title.ro)) fail(`${where}: title.ro is required`);
  if (!t.title || !isText(t.title.en)) fail(`${where}: title.en is required`);
}

// A clip's section is the n-th <h2> of the article, or "N.M" for the m-th
// <h3> inside the n-th <h2>. An empty article shows every card above it, so
// it needs no headings.
function checkClipSections(where, m, page, html, lang) {
  if (!Array.isArray(m.youtube) || m.youtube.length < 2) return;
  const article = readArticle(html, lang) || '';
  if (!Catalog.hasArticleContent(article)) return;
  const count = countHeadings(article);
  const subs = subheadingCounts(article);
  m.youtube.forEach((v, i) => {
    if (!v || v.section === undefined) return;
    const parsed = parseClipSection(v.section);
    if (!parsed) return;
    if (parsed.h2 > count) {
      fail(`${page}: youtube[${i}].section ${v.section} but the article has ${count} <h2>`);
    } else if (parsed.h3 > 0 && parsed.h3 > (subs[parsed.h2 - 1] || 0)) {
      fail(`${page}: youtube[${i}].section ${v.section} but section ${parsed.h2} has ${subs[parsed.h2 - 1] || 0} <h3>`);
    }
  });
}

// A generated clip slot is the one thing the generator inserts inside the
// article; readArticle strips it back out. If it survives, either a hand
// edit re-shaped it past what stripClipSlots recognises, or the page was
// never regenerated after a data change.
function checkNoLeftoverSlot(page, html, lang) {
  const article = readArticle(html, lang) || '';
  if (article.includes('data-generated="clips"')) {
    fail(`${page}: a generated clip slot is left inside the article; run node tools/build_pages.mjs`);
  }
}

const materialUids = new Set();
const materialNames = new Set();
const listedPdfs = new Set();
const superseding = [];
for (const [i, m] of materials.entries()) {
  const where = `material #${i}`;
  if (!m || typeof m !== 'object') { fail(`${where}: must be an object`); continue; }
  if (!isText(m.uid) || !UID_RE.test(m.uid)) {
    fail(`${where}: uid must be 4 or more digits, not starting with 0`);
  } else if (materialUids.has(m.uid)) {
    fail(`${where}: duplicate uid "${m.uid}"`);
  } else {
    materialUids.add(m.uid);
  }
  if (!isText(m.slug) || !ID_RE.test(m.slug)) {
    fail(`${where}: slug must be lowercase letters, digits and dashes`);
  }
  const name = `${m.slug || '?'}-${m.uid || '?'}`;
  if (materialNames.has(name)) fail(`${where}: duplicate material name "${name}"`);
  materialNames.add(name);
  if (!topicIds.has(m.topic)) fail(`${where}: topic "${m.topic}" does not exist`);
  if (!Catalog.KINDS.includes(m.kind)) fail(`${where}: kind must be one of ${Catalog.KINDS.join(', ')}`);
  if (!m.title || !isText(m.title.ro)) fail(`${where}: title.ro is required`);
  if (!m.title || !isText(m.title.en)) fail(`${where}: title.en is required`);
  if (!Catalog.isValidDate(m.published)) fail(`${where}: published must be a real date YYYY-MM-DD`);
  if (m.updated !== undefined) {
    if (!Catalog.isValidDate(m.updated)) fail(`${where}: updated must be a real date YYYY-MM-DD`);
    else if (m.updated < m.published) fail(`${where}: updated must not be before published`);
  }
  for (const lang of ['ro', 'en']) {
    const d = m.description && m.description[lang];
    if (!isText(d)) fail(`${where}: description.${lang} is required`);
    else if ([...d].length < 70 || [...d].length > 160) {
      fail(`${where}: description.${lang} must be 70-160 characters (is ${[...d].length})`);
    }
  }
  // seoTitle: the short <title> for search results. The page adds the grade
  // (about 19 characters), so the field itself stays short.
  if (m.seoTitle !== undefined) {
    if (!m.seoTitle || typeof m.seoTitle !== 'object' || Array.isArray(m.seoTitle)) {
      fail(`${where}: seoTitle must be { "ro": text, "en": text }`);
    } else {
      for (const key of Object.keys(m.seoTitle)) if (!['ro', 'en'].includes(key)) fail(`${where}: seoTitle: unknown field "${key}"`);
      for (const lang of ['ro', 'en']) {
        const t = m.seoTitle[lang];
        if (!isText(t)) fail(`${where}: seoTitle.${lang} is required when seoTitle is present`);
        else if ([...t].length > SEO_TITLE_MAX) fail(`${where}: seoTitle.${lang} must be at most ${SEO_TITLE_MAX} characters (is ${[...t].length})`);
      }
    }
  }
  const VIDEO_KEYS = ['id', 'uploaded', 'duration', 'title', 'section', 'description'];
  if (m.youtube !== null) {
    if (!Array.isArray(m.youtube) || m.youtube.length === 0) {
      fail(`${where}: youtube must be null or a non-empty list of clips`);
    } else {
      m.youtube.forEach((v, i) => {
        const at = `${where}: youtube[${i}]`;
        if (!v || typeof v !== 'object' || Array.isArray(v)) { fail(`${at} must be an object`); return; }
        for (const key of Object.keys(v)) if (!VIDEO_KEYS.includes(key)) fail(`${at}: unknown field "${key}"`);
        if (!(typeof v.id === 'string' && YT_RE.test(v.id))) fail(`${at}.id must be an 11-character YouTube video ID`);
        const up = YT_UPLOADED_RE.exec(String(v.uploaded || ''));
        if (!up || !Catalog.isValidDate(up[1])) fail(`${at}.uploaded must be an ISO date or date-time`);
        const dur = YT_DURATION_RE.exec(String(v.duration || ''));
        if (!dur || dur[0] === 'PT' || (!dur[1] && !dur[2] && !dur[3])) fail(`${at}.duration must be an ISO 8601 duration like "PT7M31S"`);
        if (!v.title || !isText(v.title.ro) || !isText(v.title.en)) fail(`${at}.title needs ro and en`);
        if (v.section !== undefined && !parseClipSection(v.section)) fail(`${at}.section must be a whole number from 1 or "N.M" like "4.1"`);
        if (v.description !== undefined) {
          for (const lang of ['ro', 'en']) {
            const d = v.description && v.description[lang];
            if (!isText(d)) fail(`${at}.description.${lang} is required when description is present`);
            else if ([...d].length < 70 || [...d].length > 160) fail(`${at}.description.${lang} must be 70-160 characters (is ${[...d].length})`);
          }
        }
      });
      const seen = new Set();
      let lastSection = null;
      m.youtube.forEach((v, i) => {
        if (!v || typeof v !== 'object') return;
        if (seen.has(v.id)) fail(`${where}: youtube: clip "${v.id}" appears twice`);
        seen.add(v.id);
        if (v.section !== undefined && parseClipSection(v.section)) {
          if (lastSection !== null && compareClipSections(v.section, lastSection) < 0) fail(`${where}: youtube[${i}].section must not be lower than the clip before it`);
          lastSection = v.section;
        }
      });
    }
  }
  if (m.kind === 'quiz' && m.youtube !== null) fail(`${where}: youtube must be null for a quiz`);
  if (m.keywords !== undefined) {
    const ok = m.keywords && typeof m.keywords === 'object'
      && ['ro', 'en'].every((lang) => m.keywords[lang] === undefined || (Array.isArray(m.keywords[lang]) && m.keywords[lang].every(isText)));
    if (!ok) fail(`${where}: keywords must be { "ro": [text], "en": [text] }`);
  }
  // Grade forms in keywords (audit F2): the Arabic form students type.
  // Only checked when the list exists; keywords stay optional per AGENTS.md.
  const gradeOf = topics.find((t) => t.id === m.topic)?.grade;
  if (gradeOf) {
    if (m.keywords && m.keywords.ro !== undefined && !m.keywords.ro.includes(`clasa a ${gradeOf}-a`)) {
      fail(`${where}: keywords.ro must include "clasa a ${gradeOf}-a" (audit F2)`);
    }
    if (m.keywords && m.keywords.en !== undefined && !m.keywords.en.includes(`grade ${gradeOf}`)) {
      fail(`${where}: keywords.en must include "grade ${gradeOf}" (audit F2)`);
    }
  }
  // A superseded copy is the newer half of a re-import pair: it stays visible
  // on the site but is noindex until the old copy is deleted.
  if (m.supersedes !== undefined && !UID_RE.test(String(m.supersedes || ''))) {
    fail(`${where}: supersedes must be a uid like "1005"`);
  } else if (m.supersedes !== undefined) {
    superseding.push(m);
  }
  // Visibility: exactly one of three states. Default is visible, so old
  // entries carry neither field. hidden is only ever true, visibleFrom is an
  // ISO date-time with minutes and the Europe/Bucharest offset, and the two
  // never appear together.
  if (m.hidden !== undefined && m.hidden !== true) {
    fail(`${where}: hidden must be true when present (default is visible)`);
  }
  if (m.visibleFrom !== undefined && !Visibility.isValidVisibleFrom(m.visibleFrom)) {
    fail(`${where}: visibleFrom must be "YYYY-MM-DDTHH:MM:00±HH:MM" with the Europe/Bucharest offset (was "${m.visibleFrom}")`);
  }
  if (m.hidden !== undefined && m.visibleFrom !== undefined) {
    fail(`${where}: hidden and visibleFrom never appear together`);
  }
  if (m.aliases !== undefined) {
    const ok = Array.isArray(m.aliases)
      && m.aliases.every((a) => isText(a) && ID_RE.test(a));
    if (!ok) fail(`${where}: aliases must be a list of path names (lowercase letters, digits and dashes)`);
  }
  // Provenance of the PDF: "source" (a file the teacher gave) or "generated"
  // (made from the DOCX). Older entries have no key.
  if (m.import !== undefined && (typeof m.import !== 'object' || m.import === null || Array.isArray(m.import))) {
    fail(`${where}: import must be an object like { "date", "workflow" }`);
  } else if (m.import && m.import.pdf !== undefined && m.import.pdf !== 'source' && m.import.pdf !== 'generated') {
    fail(`${where}: import.pdf must be "source" or "generated"`);
  }

  const expectedPdf = `materiale/pdf/${name}.pdf`;
  if (m.kind === 'quiz' && m.pdf !== null) {
    fail(`${where}: pdf must be null for a quiz`);
  } else if (m.pdf !== null) {
    if (m.pdf !== expectedPdf) {
      fail(`${where}: pdf must be "${expectedPdf}" or null`);
    } else if (!exists(expectedPdf)) {
      fail(`${where}: missing file ${expectedPdf}`);
    } else {
      listedPdfs.add(expectedPdf);
      if (readFileSync(join(ROOT, expectedPdf)).subarray(0, 5).toString('latin1') !== '%PDF-') fail(`${expectedPdf}: is not a PDF file`);
    }
  }

  const page = `materiale/${name}.html`;
  if (!exists(page)) { fail(`${where}: missing file ${page}`); continue; }
  const html = read(page);
  const topic = topics.find((t) => t.id === m.topic);
  if (m.kind === 'quiz') {
    if (!/^<!doctype html>/i.test(html.trimStart())) fail(`${page}: must start with <!doctype html>`);
    if (!html.includes('<html lang="ro"')) fail(`${page}: must have <html lang="ro">`);
    const back = topic ? `href="../clasa-${topic.grade}.html"` : null;
    if (!back || !html.includes(back)) fail(`${page}: must link back to ../clasa-<grade>.html`);
    if (!html.includes('<!-- seo -->') || !html.includes('<!-- /seo -->')) {
      fail(`${page}: must contain the <!-- seo --> block written by tools/build_pages.mjs`);
    }
  } else {
    if (!html.includes(`data-id="${m.uid}"`)) fail(`${page}: must contain data-id="${m.uid}"`);
    if (!html.includes('data-lang="ro"')) fail(`${page}: must contain an article with data-lang="ro"`);
    if (html.includes('data-lang="en"')) fail(`${page}: the English article lives in en/${page}`);
    if (!html.includes('data-root="../"')) fail(`${page}: body must have data-root="../"`);
    if (!html.includes(`katex@${KATEX_VERSION}/`)) fail(`${page}: must load KaTeX ${KATEX_VERSION}`);
    checkClipSections(where, m, page, html, 'ro');
    checkNoLeftoverSlot(page, html, 'ro');
    const enPage = `en/${page}`;
    if (!exists(enPage)) {
      fail(`${where}: missing file ${enPage}`);
    } else {
      const enHtml = read(enPage);
      checkClipSections(where, m, enPage, enHtml, 'en');
      checkNoLeftoverSlot(enPage, enHtml, 'en');
      if (!enHtml.includes('data-lang="en"')) fail(`${enPage}: must contain an article with data-lang="en"`);
      if (enHtml.includes('data-lang="ro"')) fail(`${enPage}: the Romanian article lives in ${page}`);
      if (!enHtml.includes('data-root="../../"')) fail(`${enPage}: body must have data-root="../../"`);
      if (!enHtml.includes(`katex@${KATEX_VERSION}/`)) fail(`${enPage}: must load KaTeX ${KATEX_VERSION}`);
      checkClassMarks(enPage, enHtml);
      checkNoAnswers(enPage, enHtml);
    }
  }
  checkClassMarks(page, html);
  checkNoAnswers(page, html);
}

// Every file must be named exactly <slug>-<uid> for a material in the data.
// byName also powers the alias checks below.
const byName = new Map();
for (const m of materials) {
  if (isText(m.uid) && UID_RE.test(m.uid) && isText(m.slug) && ID_RE.test(m.slug)) {
    byName.set(`${m.slug}-${m.uid}`, m);
  }
}

// Retired materials: a retired uid is never reused, and nextUid is a counter,
// not "highest uid + 1", so a dropped row can never hand out a uid twice.
const retired = data ? (data.retired === undefined ? [] : data.retired) : [];
if (data && !Array.isArray(retired)) {
  fail('data/materials.source.json: "retired" must be an array');
}
const retiredUids = new Set();
if (Array.isArray(retired)) {
  for (const [i, r] of retired.entries()) {
    const where = `retired #${i}`;
    if (!r || typeof r !== 'object') { fail(`${where}: must be an object`); continue; }
    if (!isText(r.uid) || !UID_RE.test(r.uid)) fail(`${where}: uid must be 4 or more digits, not starting with 0`);
    else if (retiredUids.has(r.uid)) fail(`${where}: duplicate retired uid "${r.uid}"`);
    retiredUids.add(r.uid);
    if (!isText(r.slug) || !ID_RE.test(r.slug)) fail(`${where}: slug must be lowercase letters, digits and dashes`);
    if (!Catalog.isValidDate(r.removed)) fail(`${where}: removed must be a real date YYYY-MM-DD`);
    if (r.replacedBy !== null && r.replacedBy !== undefined && !UID_RE.test(String(r.replacedBy || ''))) {
      fail(`${where}: replacedBy must be a uid or null`);
    }
  }
  for (const uid of retiredUids) {
    if (materialUids.has(uid)) fail(`data/materials.source.json: uid "${uid}" appears both in materials and in retired`);
  }
}

// The counter only ever goes up and must stay ahead of every uid that exists.
const nextUid = data ? data.nextUid : undefined;
if (data && !Number.isInteger(nextUid)) {
  fail('data/materials.source.json: "nextUid" counter must be a number');
} else if (data) {
  const taken = [...materialUids, ...retiredUids].map(Number);
  if (taken.some((n) => nextUid <= n)) {
    fail(`data/materials.source.json: nextUid (${nextUid}) must be larger than every uid in materials and retired (max ${Math.max(...taken)})`);
  }
}

// supersedes names a real uid, and both pages of the newer copy stay noindex.
for (const m of superseding) {
  const name = `${m.slug}-${m.uid}`;
  if (!materialUids.has(m.supersedes) && !retiredUids.has(m.supersedes)) {
    fail(`material ${name}: supersedes "${m.supersedes}" does not name a live or retired uid`);
  }
  for (const page of m.kind === 'quiz' ? [`materiale/${name}.html`] : [`materiale/${name}.html`, `en/materiale/${name}.html`]) {
    if (!exists(page)) continue;
    const html = read(page);
    if (!html.includes('noindex, follow')) fail(`${page}: superseded material must be noindex`);
    if (html.includes('max-image-preview')) fail(`${page}: a noindex page must not contain max-image-preview`);
  }
}

// A not-visible material (hidden or scheduled) keeps its page, because the
// article lives in that file, but the page stays noindex until it is revealed.
for (const m of materials) {
  if (Visibility.isVisible(m)) continue;
  const name = `${m.slug}-${m.uid}`;
  for (const page of m.kind === 'quiz' ? [`materiale/${name}.html`] : [`materiale/${name}.html`, `en/materiale/${name}.html`]) {
    if (!exists(page)) continue;
    const html = read(page);
    if (!html.includes('noindex, follow')) fail(`${page}: not-visible material must be noindex`);
    if (html.includes('max-image-preview')) fail(`${page}: a noindex page must not contain max-image-preview`);
  }
}

// The public copy the browser fetches: visible materials only, no nextUid,
// no retired. The --check staleness rule above already pins it byte for byte
