// Marks of one school class (not of the grade). Materials are shared with other classes, so they must not show them.
const CLASS_MARKS = [
  [/\b[IVX]+-a\s+[A-Z]\d\b/, 'a class name like "IX-a R2"'],
  [/\b(?:[5-9]|1[0-2])[A-Z]\d\b/, 'a class code like "9R2"'],
  [/\bS\d{1,2}\s*:\s*\d/, 'a school week like "S2: 14"'],
  [/\b\d{1,2}\.\d{1,2}\.20\d{2}\b/, 'a calendar date like "16.09.2026"'],
];
const ANSWER_HEADINGS = ['raspunsuri si indicatii', 'barem de evaluare', 'indicatii de rezolvare'];

function walk(dir, out = []) {
  for (const name of readdirSync(join(ROOT, dir))) {
    if (name.startsWith('.') || ['node_modules', 'docs', 'tests', 'tools'].includes(name)) continue;
    const rel = dir ? `${dir}/${name}` : name;
    if (statSync(join(ROOT, rel)).isDirectory()) walk(rel, out);
    else out.push(rel);
  }
  return out;
}

// YouTube ids of the materials. An id cannot be changed, and one such as
// "ab-9R2xyzAB" reads like a class code, so the class-mark scan skips them.
const VIDEO_IDS = new Set();

function checkClassMarks(where, text) {
  for (const id of VIDEO_IDS) text = text.split(id).join('');
  for (const [re, what] of CLASS_MARKS) {
    const hit = text.match(re);
    if (hit) fail(`${where}: contains ${what} ("${hit[0]}"). Remove class-specific details.`);
  }
}

// Answers live only in data/results/ and tm25mlg/raspunsuri/ (and never in
// material pages, PDFs or the materials JSON files). The answer-heading rule
// never runs on those two folders; every other place keeps it.
function checkNoAnswers(where, text) {
  const plain = Catalog.normalize(String(text).replace(/<[^>]+>/g, ' ')).replace(/\s+/g, ' ');
  for (const phrase of ANSWER_HEADINGS) {
    if (plain.includes(phrase)) fail(`${where}: contains "${phrase}". Published materials must not include answers.`);
  }
}

